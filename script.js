function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');
}

function getVisibleProjects() {
  return projects.filter((project) => {
    if (activeDiscipline !== 'all' && project.discipline !== activeDiscipline) return false;
    if (activeCategory && project.category !== activeCategory) return false;
    return true;
  });
}

function renderProjects() {
  const visibleProjects = getVisibleProjects();
  grid.innerHTML = visibleProjects
    .map((project, index) => `
      <button
        type="button"
        class="project-card project-${escapeHtml(project.size)} project-${escapeHtml(project.id)}"
        data-project-id="${escapeHtml(project.id)}"
        style="--project-order:${index}"
      >
        <div class="project-visual">
          <img
            src="${escapeHtml(project.image)}"
            alt="${escapeHtml(project.title)} project cover"
            loading="${index < 2 ? 'eager' : 'lazy'}"
            decoding="async"
          />
          <span class="project-open">Open project ↗</span>
        </div>
        <div class="project-info">
          <div>
            <span>${escapeHtml(project.category)}</span>
            <h3>${escapeHtml(project.title)}</h3>
          </div>
          <div class="project-meta">
            <span>${escapeHtml(project.client)}</span>
            <span>${escapeHtml(project.year)}</span>
          </div>
        </div>
      </button>
    `)
    .join('');

  grid.querySelectorAll('[data-project-id]').forEach((card) => {
    card.addEventListener('click', () => {
      const project = projects.find((item) => item.id === card.dataset.projectId);
      if (project) {
        lastFocusedProject = card;
        openProject(project);
      }
    });
  });
}

function renderSecondaryFilters() {
  if (activeDiscipline === 'all') {
    secondaryFilters.hidden = true;
    secondaryFilters.innerHTML = '';
    return;
  }

  secondaryFilters.hidden = false;
  secondaryFilters.innerHTML = categories[activeDiscipline]
    .map((category, index) => `
      <button type="button" class="${index === 0 && !activeCategory ? 'is-active' : activeCategory === category ? 'is-active' : ''}" data-category="${escapeHtml(category)}">
        ${escapeHtml(category)}
      </button>
    `)
    .join('');

  secondaryFilters.querySelectorAll('[data-category]').forEach((button) => {
    button.addEventListener('click', () => {
      activeCategory = button.dataset.category.startsWith('All ') ? '' : button.dataset.category;
      renderSecondaryFilters();
      renderProjects();
    });
  });
}

function pauseMotionGraphicsVideos() {
  modalGallery.querySelectorAll('.motion-graphics-video').forEach((video) => {
    video.pause();
  });
}

function destroyVideoAutoplay() {
  if (videoAutoplayObserver) videoAutoplayObserver.disconnect();
  videoAutoplayObserver = null;
  observedVideoRatios.clear();
  pauseMotionGraphicsVideos();
}

function requestAutoplay(video) {
  if (!video || video.hidden || reducedMotionPreference.matches || document.hidden) return;

  if (video.readyState < HTMLMediaElement.HAVE_CURRENT_DATA) {
    if (video.dataset.waitingForAutoplay === 'true') return;

    video.dataset.waitingForAutoplay = 'true';
    video.addEventListener(
      'canplay',
      () => {
        delete video.dataset.waitingForAutoplay;
        updateVideoAutoplay();
      },
      { once: true }
    );
    return;
  }

  video.play().catch(() => {
    // Some browsers or user settings may still block autoplay.
  });
}

function updateVideoAutoplay() {
  const videos = [...modalGallery.querySelectorAll('.motion-graphics-video')];
  if (videos.length === 0) return;

  let activeVideo = null;
  let highestRatio = 0;

  videos.forEach((video) => {
    const ratio = observedVideoRatios.get(video) || 0;
    if (!video.hidden && ratio > highestRatio) {
      highestRatio = ratio;
      activeVideo = video;
    }
  });

  // Require most of a video to be visible before it starts playing.
  if (highestRatio < 0.6 || reducedMotionPreference.matches || document.hidden) {
    activeVideo = null;
  }

  videos.forEach((video) => {
    if (video === activeVideo) requestAutoplay(video);
    else video.pause();
  });
}

function initializeVideoAutoplay() {
  destroyVideoAutoplay();

  const videos = [...modalGallery.querySelectorAll('.motion-graphics-video')];
  if (videos.length === 0 || reducedMotionPreference.matches || !('IntersectionObserver' in window)) return;

  observedVideoRatios = new Map(videos.map((video) => [video, 0]));
  videoAutoplayObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        observedVideoRatios.set(entry.target, entry.isIntersecting ? entry.intersectionRatio : 0);
      });
      updateVideoAutoplay();
    },
    {
      root: modal,
      rootMargin: '-8% 0px -8% 0px',
      threshold: [0, 0.25, 0.45, 0.6, 0.75, 0.9, 1],
    }
  );

  videos.forEach((video) => videoAutoplayObserver.observe(video));
}

function createProjectGallery(project) {
  destroyVideoAutoplay();
  modalGallery.replaceChildren();
  modalGallery.className = 'project-case-study';

  if (!project.gallery) {
    modalGallery.hidden = true;
    modalScrollCue.hidden = true;
    caseStudyEnd.hidden = true;
    modalNote.hidden = false;
    modalArticle.classList.remove('has-case-study');
    return;
  }

  const videoItems = Array.isArray(project.gallery.videos)
    ? project.gallery.videos.map((item) => (typeof item === 'string' ? { src: item } : item))
    : [];

  if (videoItems.length > 0) {
    createVideoGallery(project, videoItems);
    return;
  }

  const galleryItems = Array.isArray(project.gallery.images)
    ? project.gallery.images.map((item) => (typeof item === 'string' ? { src: item } : item))
    : [];

  if (galleryItems.length === 0) {
    modalGallery.hidden = true;
    modalScrollCue.hidden = true;
    caseStudyEnd.hidden = true;
    modalNote.hidden = false;
    modalArticle.classList.remove('has-case-study');
    return;
  }

  if (project.gallery.layout) modalGallery.classList.add(project.gallery.layout);

  const fragment = document.createDocumentFragment();

  galleryItems.forEach((item, index) => {
    const figure = document.createElement('figure');
    figure.className = 'case-study-frame';

    const image = document.createElement('img');
    image.alt = item.alt || `${project.title} presentation — image ${index + 1}`;
    image.loading = index < 2 ? 'eager' : 'lazy';
    image.decoding = 'async';

    const markLoaded = () => figure.classList.add('is-loaded');
    const removeMissing = () => {
      figure.remove();
      checkGalleryEmpty();
    };

    // Register handlers before assigning src so cached images are handled too.
    image.addEventListener('load', markLoaded, { once: true });
    image.addEventListener('error', removeMissing, { once: true });
    image.src = item.src;

    if (image.complete) {
      if (image.naturalWidth > 0) markLoaded();
      else removeMissing();
    }

    figure.appendChild(image);

    if (item.title) {
      const caption = document.createElement('figcaption');
      caption.innerHTML = `<span>${String(index + 1).padStart(2, '0')}</span><strong>${escapeHtml(item.title)}</strong>`;
      figure.appendChild(caption);
      figure.classList.add('has-caption');
    }

    fragment.appendChild(figure);
  });

  modalGallery.appendChild(fragment);
  modalGallery.hidden = false;
  modalScrollCue.hidden = false;
  caseStudyEnd.hidden = false;
  modalNote.hidden = true;
  modalArticle.classList.add('has-case-study');
}

function createVideoGallery(project, videoItems) {
  if (project.gallery.layout) modalGallery.classList.add(project.gallery.layout);

  const fragment = document.createDocumentFragment();

  videoItems.forEach((item, index) => {
    const figure = document.createElement('figure');
    figure.className = 'case-study-frame video-case-study-frame';

    const videoShell = document.createElement('div');
    videoShell.className = 'video-shell';

    const video = document.createElement('video');
    video.className = 'motion-graphics-video';
    video.controls = true;
    video.loop = true;
    video.muted = true;
    video.defaultMuted = true;
    video.preload = 'metadata';
    video.playsInline = true;
    video.hidden = true;
    video.setAttribute('muted', '');
    video.setAttribute('loop', '');
    video.setAttribute('playsinline', '');
    video.setAttribute('aria-label', item.title || `${project.title} video ${index + 1}`);

    const placeholder = document.createElement('div');
    placeholder.className = 'video-placeholder';
    const filename = item.src.split('/').pop();
    placeholder.innerHTML = `
      <span>Expected video file</span>
      <strong>${escapeHtml(filename)}</strong>
      <code>${escapeHtml(item.src)}</code>
      <small>Add the MP4 to the prepared folder and it will appear here automatically.</small>
    `;

    const markLoaded = () => {
      figure.classList.add('is-loaded', 'has-video');
      placeholder.hidden = true;
      video.hidden = false;

      // Match the player shell to the actual export ratio. This keeps
      // landscape montages, vertical reels, and standard 16:9 videos from
      // being cropped or surrounded by unnecessary empty space.
      if (video.videoWidth > 0 && video.videoHeight > 0) {
        videoShell.style.aspectRatio = `${video.videoWidth} / ${video.videoHeight}`;
      }

      updateVideoAutoplay();
    };

    const markMissing = () => {
      figure.classList.add('is-loaded', 'is-missing');
      video.hidden = true;
      placeholder.hidden = false;
    };

    video.addEventListener('loadedmetadata', markLoaded, { once: true });
    video.addEventListener('error', markMissing, { once: true });
    video.addEventListener('play', () => {
      modalGallery.querySelectorAll('.motion-graphics-video').forEach((otherVideo) => {
        if (otherVideo !== video) otherVideo.pause();
      });
    });
    video.src = item.src;

    videoShell.append(video, placeholder);
    figure.appendChild(videoShell);

    const caption = document.createElement('figcaption');
    caption.innerHTML = `<span>${String(index + 1).padStart(2, '0')}</span><strong>${escapeHtml(item.title || `Motion Graphics ${index + 1}`)}</strong>`;
    figure.appendChild(caption);
    figure.classList.add('has-caption');

    fragment.appendChild(figure);
  });

  modalGallery.appendChild(fragment);
  modalGallery.hidden = false;
  modalScrollCue.hidden = false;
  caseStudyEnd.hidden = false;
  modalNote.hidden = true;
  modalArticle.classList.add('has-case-study');
}

// If every image in the gallery fails to load (e.g. wrong folder/prefix,
// or the images were never uploaded), fall back to the note instead of
// silently showing an empty case study.
function checkGalleryEmpty() {
  if (modalGallery.children.length === 0) {
    modalGallery.hidden = true;
    modalScrollCue.hidden = true;
    caseStudyEnd.hidden = true;
    modalNote.hidden = false;
    modalArticle.classList.remove('has-case-study');
  }
}

function openProject(project) {
  modal.scrollTop = 0;
  modalImage.src = project.image;
  modalImage.alt = `${project.title} project cover`;
  modalEyebrow.textContent = `${project.category} / ${project.year}`;
  modalTitle.textContent = project.title;
  modalClient.textContent = project.client;
  modalSummary.textContent = project.summary;
  modalTags.innerHTML = project.tags.map((tag) => `<span>${escapeHtml(tag)}</span>`).join('');
  createProjectGallery(project);

  modal.hidden = false;
  document.body.classList.add('modal-open');
  initializeVideoAutoplay();
  modal.querySelector('[data-close-modal]').focus();
}

function closeProject() {
  destroyVideoAutoplay();
  modal.hidden = true;
  document.body.classList.remove('modal-open');
  modalGallery.replaceChildren();
  modalArticle.classList.remove('has-case-study');
  if (lastFocusedProject) lastFocusedProject.focus();
}

disciplineButtons.forEach((button) => {
  button.addEventListener('click', () => {
    activeDiscipline = button.dataset.discipline;
    activeCategory = '';
    disciplineButtons.forEach((item) => item.classList.toggle('is-active', item === button));
    renderSecondaryFilters();
    renderProjects();
  });
});

modal.addEventListener('mousedown', (event) => {
  if (event.target === modal) closeProject();
});
modal.querySelectorAll('[data-close-modal]').forEach((button) => {
  button.addEventListener('click', closeProject);
});
window.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && !modal.hidden) closeProject();
});

